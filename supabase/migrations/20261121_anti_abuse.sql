-- ============================================================
-- DATE-15 荒らし対策マイグレーション（Issue #3〜#6）
--
--   #3 NGワードチェックをサーバー側（Supabase）でも必須にする
--   #4 通報ボタンと非表示（モデレーション）
--   #5 NG判定の表記ゆれ対策とワードリスト拡充
--   #6 連投制限といいねの多重対策（サーバー側の上限）
--
-- 適用方法:
--   Supabase ダッシュボード（SQL Editor）でこのファイル全体を実行するか、
--   Management API の database/query に本文を渡す。
--   何度実行しても同じ状態になるよう if not exists / or replace で書いてある。
--
-- 語彙について:
--   NGワードの配列は ng-check.js（ブラウザと単体テストが使う語彙）を
--   正規化したものと完全に一致させる。片側だけ直すと素通りが生まれるため、
--   tests/moderation.test.js が両者の一致を検証する。
--   ng-check.js を直したら `npm run ng:sql` でこの配列を再生成して貼り直す。
--
-- 正規化（日英・全半角・カナ・記号・長音のゆれ吸収）:
--   1) NFKC（半角カナ→全角カナ、全角英数→半角）
--   2) 小文字化
--   3) カタカナ→ひらがな
--   4) 英数字・ひらがな・漢字以外（空白・記号・中点・長音「ー」）を除去
--   ng-check.js の normalize() と同じ手順。SQL 側だけ NFKC を使っており、
--   ブラウザは String.prototype.normalize('NFKC') を使う（結果は同じ）。
-- ============================================================

-- ------------------------------------------------------------
-- 1. date_plans に hidden / device_id を追加
-- ------------------------------------------------------------
alter table public.date_plans add column if not exists hidden boolean not null default false;
alter table public.date_plans add column if not exists device_id text;

create index if not exists date_plans_hidden_idx
  on public.date_plans (hidden);

create index if not exists date_plans_device_created_idx
  on public.date_plans (device_id, created_at desc);

-- ------------------------------------------------------------
-- 2. 通報テーブル（1通報=1行。誰がどの投稿を通報したかは端末IDのみ）
-- ------------------------------------------------------------
create table if not exists public.date_plan_reports (
  id bigint generated by default as identity primary key,
  plan_id bigint not null,
  reason text not null default 'inappropriate',
  device_id text,
  created_at timestamptz not null default now()
);

create index if not exists date_plan_reports_plan_idx
  on public.date_plan_reports (plan_id);

-- 通報の読み出しは運営（service_role / ダッシュボード）だけ。
-- 匿名キーからは INSERT のみ許可する（誰の通報か一覧を覗けない）。
alter table public.date_plan_reports enable row level security;

drop policy if exists date15_reports_insert on public.date_plan_reports;
create policy date15_reports_insert
  on public.date_plan_reports
  for insert
  to anon, authenticated
  with check (true);

grant insert on public.date_plan_reports to anon, authenticated;

-- ------------------------------------------------------------
-- 3. 判定用の正規化関数（ng-check.js の normalize と同じ）
-- ------------------------------------------------------------
create or replace function public.date15_normalize(p_text text)
returns text
language plpgsql
immutable
as $$
declare
  s text;
  ch text;
  out text := '';
  i int;
begin
  if p_text is null then
    return '';
  end if;

  -- 1) NFKC + 小文字化
  s := lower(normalize(p_text, NFKC));

  -- 2) カタカナ（ァ U+30A1 = 12449 〜 ヶ U+30F6 = 12534）→ ひらがな
  for i in 1..char_length(s) loop
    ch := substr(s, i, 1);
    if ascii(ch) between 12449 and 12534 then
      out := out || chr(ascii(ch) - 96);
    else
      out := out || ch;
    end if;
  end loop;

  -- 3) 英数字・ひらがな・漢字以外を除去（空白・記号・中点・長音も落ちる）
  out := regexp_replace(out, '[^0-9a-zぁ-ゖ一-龥]', '', 'g');
  return out;
end;
$$;

