-- ------------------------------------------------------------
-- 5. 投稿のサーバー側チェック（REST API への直接 POST でも通さない）
--    Issue #3: NG判定の必須化 / #5: 表記ゆれ / #6: 連投上限
-- ------------------------------------------------------------
create or replace function public.date15_guard_plan()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  n text;
  w text;
  recent int;
begin
  -- 15文字ちょうど・空白なし（クライアントと同じ条件）
  if new.text is null or new.text ~ '[[:space:]　]' then
    raise exception 'date15_length: 15文字ちょうどで、空白なしで入力してください'
      using errcode = 'P0001';
  end if;
  if char_length(new.text) <> 15 then
    raise exception 'date15_length: 15文字ちょうどで入力してください'
      using errcode = 'P0001';
  end if;

  -- NGワード（表記ゆれ吸収済み）
  n := date15_normalize(new.text);
  foreach w in array date15_ng_words() loop
    if w <> '' and position(w in n) > 0 then
      raise exception 'date15_ng: 不適切な表現が含まれています'
        using errcode = 'P0001';
    end if;
  end loop;

  -- リンク・メール・電話番号
  if new.text ~* '(https?://|www\.)' then
    raise exception 'date15_link: リンクは投稿できません' using errcode = 'P0001';
  end if;
  if new.text ~* '[a-z0-9-]+\.(com|net|org|jp|io|me|ly|app|co)([^a-z0-9]|$)' then
    raise exception 'date15_link: リンクは投稿できません' using errcode = 'P0001';
  end if;
  if new.text ~* '[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}' then
    raise exception 'date15_link: 連絡先は投稿できません' using errcode = 'P0001';
  end if;
  if regexp_replace(new.text, '[^0-9]', '', 'g') ~ '^[0-9]{10,11}$' then
    raise exception 'date15_link: 連絡先は投稿できません' using errcode = 'P0001';
  end if;

  -- 投稿者名（未入力なら匿名希望）も同じ基準で見る
  n := date15_normalize(coalesce(new.author, ''));
  foreach w in array date15_ng_words() loop
    if w <> '' and position(w in n) > 0 then
      raise exception 'date15_author: ニックネームに不適切な表現が含まれています'
        using errcode = 'P0001';
    end if;
  end loop;

  -- 連投制限: 同じ端末IDから60秒に1件まで（クライアントの制限の裏付け）
  if new.device_id is not null and length(new.device_id) > 0 then
    select count(*) into recent
      from public.date_plans
     where device_id = new.device_id
       and created_at > now() - interval '60 seconds';
    if recent > 0 then
      raise exception 'date15_rate_limited: 連投を防ぐため、しばらく待ってから投稿してください'
        using errcode = 'P0001';
    end if;
  end if;

  return new;
end;
$$;

drop trigger if exists date15_guard_plan_trg on public.date_plans;
create trigger date15_guard_plan_trg
  before insert on public.date_plans
  for each row
  execute function public.date15_guard_plan();

-- 既存の行を書き換えてNG文言を持ち込む経路も塞ぐ
create or replace function public.date15_guard_plan_update()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.text is distinct from old.text or new.author is distinct from old.author then
    -- before update では date15_guard_plan をそのまま呼べる（NEW を検証するだけ）
    return date15_guard_plan();
  end if;
  return new;
end;
$$;

drop trigger if exists date15_guard_plan_update_trg on public.date_plans;
create trigger date15_guard_plan_update_trg
  before update on public.date_plans
  for each row
  execute function public.date15_guard_plan_update();

-- ------------------------------------------------------------
-- 6. 通報が3件たまった投稿は自動で非表示（Issue #4）
-- ------------------------------------------------------------
create or replace function public.date15_handle_report()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  cnt int;
begin
  if not exists (select 1 from public.date_plans where id = new.plan_id) then
    raise exception 'date15_unknown_plan: 通報先の投稿が見つかりません'
      using errcode = 'P0001';
  end if;

  select count(*) into cnt
    from public.date_plan_reports
   where plan_id = new.plan_id;

  if cnt >= 3 then
    update public.date_plans
       set hidden = true
     where id = new.plan_id
       and hidden = false;
  end if;

  return new;
end;
$$;

drop trigger if exists date15_handle_report_trg on public.date_plan_reports;
create trigger date15_handle_report_trg
  after insert on public.date_plan_reports
  for each row
  execute function public.date15_handle_report();
